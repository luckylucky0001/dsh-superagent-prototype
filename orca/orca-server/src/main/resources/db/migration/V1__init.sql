-- Orca schema. Portable between PostgreSQL and H2 (PostgreSQL mode). Times are epoch millis.

create table member (
  id varchar(40) primary key,
  email varchar(200) not null unique,
  name varchar(200) not null,
  password_hash varchar(200),
  role varchar(20) not null,
  created_at bigint not null
);

create table api_token (
  id varchar(40) primary key,
  kind varchar(20) not null,
  token_hash varchar(100) not null unique,
  member_id varchar(40),
  runtime_id varchar(40),
  label varchar(200),
  expires_at bigint,
  used_at bigint,
  created_at bigint not null
);

create table runtime (
  id varchar(40) primary key,
  name varchar(200) not null,
  hostname varchar(200),
  os varchar(200),
  daemon_version varchar(40),
  capacity int not null,
  isolated boolean not null,
  status varchar(20) not null,
  last_seen_at bigint,
  providers_json text,
  created_at bigint not null
);

create table project (
  id varchar(40) primary key,
  key_prefix varchar(20) not null unique,
  name varchar(200) not null,
  description text,
  repo_url varchar(500),
  default_branch varchar(200),
  next_number int not null,
  created_at bigint not null
);

create table agent (
  id varchar(40) primary key,
  name varchar(100) not null unique,
  description text,
  provider varchar(20) not null,
  runtime_id varchar(40),
  model varchar(100),
  effort varchar(40),
  instructions text,
  permission varchar(20) not null,
  allowed_commands_json text,
  extra_args_json text,
  max_concurrency int not null,
  timeout_minutes int not null,
  archived boolean not null,
  created_at bigint not null,
  updated_at bigint not null
);

create table issue (
  id varchar(40) primary key,
  project_id varchar(40) not null,
  number int not null,
  issue_key varchar(40) not null unique,
  title varchar(500) not null,
  description text,
  status varchar(20) not null,
  priority varchar(20) not null,
  assignee_type varchar(20),
  assignee_id varchar(40),
  labels_json text,
  created_by varchar(40),
  created_at bigint not null,
  updated_at bigint not null
);
create index issue_project_status on issue(project_id, status);

create table comment (
  id varchar(40) primary key,
  issue_id varchar(40) not null,
  author_type varchar(20) not null,
  author_id varchar(40),
  body text not null,
  task_id varchar(40),
  created_at bigint not null
);
create index comment_issue on comment(issue_id, created_at);

create table task (
  id varchar(40) primary key,
  agent_id varchar(40) not null,
  runtime_id varchar(40),
  issue_id varchar(40),
  provider varchar(20) not null,
  kind varchar(20) not null,
  origin_json text,
  prompt text not null,
  recap text,
  output_schema_json text,
  status varchar(20) not null,
  status_detail varchar(500),
  session_ref varchar(200),
  resume_ref varchar(200),
  workspace_key varchar(300) not null,
  model varchar(100),
  final_text text,
  structured_json text,
  error_code varchar(40),
  error text,
  usage_json text,
  last_seq bigint not null,
  lease_until bigint,
  queued_at bigint not null,
  started_at bigint,
  finished_at bigint
);
create index task_status on task(status, queued_at);
create index task_issue on task(issue_id, queued_at);
create index task_agent on task(agent_id, status);

create table task_event (
  id bigint generated by default as identity primary key,
  task_id varchar(40) not null,
  seq bigint not null,
  type varchar(40) not null,
  ts bigint not null,
  data_json text,
  unique (task_id, seq)
);

create table workflow (
  id varchar(40) primary key,
  name varchar(200) not null,
  description text,
  enabled boolean not null,
  built_in boolean not null,
  current_version int not null,
  definition_json text not null,
  created_at bigint not null,
  updated_at bigint not null
);

create table workflow_version (
  id varchar(40) primary key,
  workflow_id varchar(40) not null,
  version int not null,
  definition_json text not null,
  created_by varchar(40),
  created_at bigint not null,
  unique (workflow_id, version)
);

create table workflow_run (
  id varchar(40) primary key,
  workflow_id varchar(40) not null,
  version int not null,
  status varchar(20) not null,
  trigger_node_id varchar(80) not null,
  issue_id varchar(40),
  state_json text not null,
  error text,
  started_at bigint not null,
  finished_at bigint,
  lock_version bigint not null
);
create index run_workflow on workflow_run(workflow_id, started_at);
create index run_status on workflow_run(status);

create table inbox_item (
  id varchar(40) primary key,
  kind varchar(20) not null,
  status varchar(20) not null,
  title varchar(500) not null,
  body text,
  form_json text,
  answer_json text,
  task_id varchar(40),
  request_id varchar(80),
  run_id varchar(40),
  node_id varchar(80),
  wait_key varchar(200),
  issue_id varchar(40),
  created_at bigint not null,
  resolved_at bigint,
  resolved_by varchar(40)
);
create index inbox_status on inbox_item(status, created_at);

create table schedule_state (
  id varchar(140) primary key,
  workflow_id varchar(40) not null,
  node_id varchar(80) not null,
  next_fire_at bigint not null
);

#!/usr/bin/env python3
"""Writes THIRD-PARTY-NOTICES.md: the open-source components shipped in the server, daemon and CLI jars and in
the web bundle, with their licences.

Run from the repository root after a build (needs ~/.m2 populated and web/node_modules installed):
    python3 scripts/third-party-notices.py
"""
import json
import os
import re
import subprocess
import sys
import tempfile
import xml.etree.ElementTree as ET

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
M2 = os.path.expanduser("~/.m2/repository")
MODULES = ["fellowloop-server", "fellowloop-daemon", "fellowloop-cli"]
NS = {"m": "http://maven.apache.org/POM/4.0.0"}


def maven_deps():
    deps = {}
    with tempfile.TemporaryDirectory() as tmp:
        for m in MODULES:
            out = os.path.join(tmp, m + ".txt")
            subprocess.run(["mvn", "-q", "-pl", m, "dependency:list", "-DincludeScope=runtime",
                            "-DexcludeGroupIds=dev.fellowloop", "-DoutputFile=" + out], cwd=ROOT, check=True)
            for line in open(out, encoding="utf-8"):
                line = re.sub(r"\x1b\[[0-9;]*m", "", line).strip()
                parts = line.split(" ")[0].split(":")
                if len(parts) >= 5:
                    g, a, v = parts[0], parts[1], parts[-2]
                    deps.setdefault((g, a, v), set()).add(m)
    return deps


def pom(g, a, v):
    p = os.path.join(M2, *g.split("."), a, v, f"{a}-{v}.pom")
    return ET.parse(p).getroot() if os.path.exists(p) else None


def text(el, path):
    x = el.find(path, NS)
    if x is None:
        x = el.find(path.replace("m:", ""))
    return x.text.strip() if x is not None and x.text else None


def licences(g, a, v, depth=0):
    root = pom(g, a, v)
    if root is None or depth > 6:
        return []
    found = []
    for lic in list(root.findall("m:licenses/m:license", NS)) + list(root.findall("licenses/license")):
        found.append((text(lic, "m:name") or "?", text(lic, "m:url") or ""))
    if found:
        return found
    parent = root.find("m:parent", NS)
    if parent is None:
        parent = root.find("parent")
    if parent is not None:
        return licences(text(parent, "m:groupId"), text(parent, "m:artifactId"), text(parent, "m:version"), depth + 1)
    return []


def npm_deps():
    web = os.path.join(ROOT, "web")
    tree = json.loads(subprocess.run(["npm", "ls", "--omit=dev", "--all", "--json"], cwd=web,
                                     capture_output=True, text=True).stdout or "{}")
    seen = {}

    def walk(node):
        for name, d in (node.get("dependencies") or {}).items():
            key = (name, d.get("version"))
            if key in seen or not d.get("version"):
                continue
            pj = os.path.join(web, "node_modules", name, "package.json")
            lic = "?"
            if os.path.exists(pj):
                meta = json.load(open(pj, encoding="utf-8"))
                lic = meta.get("license") or (meta.get("licenses") or [{}])[0].get("type", "?")
                if isinstance(lic, dict):
                    lic = lic.get("type", "?")
            seen[key] = lic
            walk(d)

    walk(tree)
    return seen


def main():
    rows = []
    for (g, a, v), mods in sorted(maven_deps().items()):
        lic = licences(g, a, v)
        rows.append((f"{g}:{a}", v, "; ".join(n for n, _ in lic) or "see project", ", ".join(sorted(mods)),
                     next((u for _, u in lic if u), "")))
    npm = npm_deps()
    out = ["# Third-party notices", "",
           "Fellowloop ships the open-source components below. Each is used under its own licence; the licence texts are "
           "at the linked addresses and, for Apache-2.0 components, in the `META-INF` folder of each component's jar "
           "(kept inside the Fellowloop jars). Generated by `scripts/third-party-notices.py`.", "",
           "Codex CLI and TRAE CLI are not part of Fellowloop: each runtime machine installs them from their vendors and "
           "uses them under the vendors' terms.", "",
           "Dual-licensed components (Logback EPL-2.0/LGPL-2.1, Jakarta APIs EPL-2.0/GPL-2.0 with Classpath "
           "Exception) are used under the EPL-2.0 option; H2 under MPL-2.0. All are shipped unmodified; their source "
           "is available from the projects.", "",
           f"## Java (server, daemon, CLI): {len(rows)} components", "",
           "| Component | Version | Licence | Used by |", "|---|---|---|---|"]
    for name, v, lic, mods, url in rows:
        out.append(f"| {name} | {v} | {f'[{lic}]({url})' if url else lic} | {mods} |")
    out += ["", f"## Web app (bundled into the server): {len(npm)} packages", "", "| Package | Version | Licence |",
            "|---|---|---|"]
    for (name, v), lic in sorted(npm.items()):
        out.append(f"| {name} | {v} | {lic} |")
    unknown = [r[0] for r in rows if r[2] == "see project"] + [n for (n, _), l in npm.items() if l == "?"]
    with open(os.path.join(ROOT, "THIRD-PARTY-NOTICES.md"), "w", encoding="utf-8") as f:
        f.write("\n".join(out) + "\n")
    print(f"{len(rows)} Java, {len(npm)} npm; unknown licence: {unknown or 'none'}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
